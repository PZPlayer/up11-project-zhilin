-- ---------- 1. Очистка (скрипт можно запускать повторно) ----------
DROP VIEW  IF EXISTS v_order_totals CASCADE;
DROP VIEW  IF EXISTS v_catalog CASCADE;
DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS stock_items CASCADE;
DROP TABLE IF EXISTS models CASCADE;
DROP TABLE IF EXISTS manufacturers CASCADE;
DROP TABLE IF EXISTS subcategories CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS variants CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS roles CASCADE;

-- ---------- 2. Справочники ----------
CREATE TABLE roles (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(40) NOT NULL UNIQUE CHECK (name <> '')
);

CREATE TABLE categories (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL UNIQUE CHECK (name <> '')
);

CREATE TABLE subcategories (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER     NOT NULL REFERENCES categories(id),
    name        VARCHAR(60) NOT NULL CHECK (name <> ''),
    UNIQUE (category_id, name)
);

CREATE TABLE manufacturers (            -- поле «Производство»
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE CHECK (name <> '')
);

CREATE TABLE variants (                 -- вариант исполнения: цвет корпуса
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(40) NOT NULL UNIQUE CHECK (name <> '')
);

-- ---------- 3. Пользователи ----------
CREATE TABLE users (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login       VARCHAR(40) NOT NULL UNIQUE CHECK (login <> ''),
    last_name   VARCHAR(60) NOT NULL CHECK (last_name <> ''),
    first_name  VARCHAR(60) NOT NULL CHECK (first_name <> ''),
    middle_name VARCHAR(60) NOT NULL DEFAULT '',
    role_id     INTEGER     NOT NULL REFERENCES roles(id)
);

-- ---------- 4. Каталог ----------
CREATE TABLE models (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120) NOT NULL CHECK (name <> ''),
    manufacturer_id INTEGER      NOT NULL REFERENCES manufacturers(id),
    subcategory_id  INTEGER      NOT NULL REFERENCES subcategories(id),
    image           VARCHAR(100) NOT NULL DEFAULT '',          -- пусто = показываем picture.png
    description     TEXT         NOT NULL DEFAULT '',
    composition     TEXT         NOT NULL DEFAULT '',
    base_price      NUMERIC(12,2) NOT NULL CHECK (base_price >= 0), -- = минимальная цена вариантов
    UNIQUE (name, manufacturer_id)                              -- модель = наименование + производство
);

CREATE TABLE stock_items (              -- товарная позиция: модель + вариант
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id   INTEGER       NOT NULL REFERENCES models(id),
    variant_id INTEGER       NOT NULL REFERENCES variants(id),
    quantity   INTEGER       NOT NULL DEFAULT 0 CHECK (quantity >= 0),   -- доступный остаток, шт.
    price      NUMERIC(12,2) NOT NULL CHECK (price >= 0),                -- цена варианта
    UNIQUE (model_id, variant_id)
);

-- ---------- 5. Заказы ----------
CREATE TABLE orders (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date DATE    NOT NULL DEFAULT CURRENT_DATE,
    client_id  INTEGER NOT NULL REFERENCES users(id)
);

CREATE TABLE order_items (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      INTEGER       NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    stock_item_id INTEGER       NOT NULL REFERENCES stock_items(id),
    quantity      INTEGER       NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),   -- историческая цена на момент заказа
    UNIQUE (order_id, stock_item_id)                                -- повторное добавление объединяется
);

-- ---------- 6. Индексы по внешним ключам ----------
CREATE INDEX idx_subcategories_category ON subcategories(category_id);
CREATE INDEX idx_users_role             ON users(role_id);
CREATE INDEX idx_models_manufacturer    ON models(manufacturer_id);
CREATE INDEX idx_models_subcategory     ON models(subcategory_id);
CREATE INDEX idx_stock_items_model      ON stock_items(model_id);
CREATE INDEX idx_stock_items_variant    ON stock_items(variant_id);
CREATE INDEX idx_orders_client          ON orders(client_id);
CREATE INDEX idx_order_items_order      ON order_items(order_id);
CREATE INDEX idx_order_items_stock      ON order_items(stock_item_id);

-- ---------- 7. Представления ----------
CREATE VIEW v_catalog AS                -- модель с категорией, производством и суммарным остатком
SELECT m.id AS model_id, m.name AS model_name, mf.name AS manufacturer,
       c.name AS category, sc.name AS subcategory, m.base_price,
       COALESCE(SUM(si.quantity), 0) AS total_stock
FROM models m
JOIN manufacturers mf ON mf.id = m.manufacturer_id
JOIN subcategories sc ON sc.id = m.subcategory_id
JOIN categories c     ON c.id  = sc.category_id
LEFT JOIN stock_items si ON si.model_id = m.id
GROUP BY m.id, m.name, mf.name, c.name, sc.name, m.base_price;

CREATE VIEW v_order_totals AS           -- итог по каждому заказу
SELECT o.id AS order_id, o.order_date,
       u.last_name || ' ' || u.first_name || ' ' || u.middle_name AS client,
       SUM(oi.quantity * oi.unit_price) AS total
FROM orders o
JOIN users u        ON u.id = o.client_id
JOIN order_items oi ON oi.order_id = o.id
GROUP BY o.id, o.order_date, u.last_name, u.first_name, u.middle_name;

