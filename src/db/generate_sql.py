# -*- coding: utf-8 -*-
"""Импорт данных: docs-import/*.xlsx  ->  src/db/mir_gadgetov.sql (PostgreSQL) и mir_gadgetov.db (SQLite-копия).

Запуск из корня репозитория:   python src/db/generate_sql.py
Нужен пакет openpyxl.  Перед записью выполняются проверки целостности данных.
"""
import re
import sqlite3
import sys
from collections import defaultdict
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parents[2]
IMPORT = ROOT / "docs-import"
OUT_SQL = ROOT / "src" / "db" / "mir_gadgetov.sql"
OUT_DB = ROOT / "src" / "db" / "mir_gadgetov.db"
IMAGES = ROOT / "src" / "resources" / "Images"

# ----------------------------------------------------------------------------
#  Схема PostgreSQL (3НФ). Этот же текст (с заменами, см. to_sqlite) создаёт SQLite-копию
# ----------------------------------------------------------------------------
SCHEMA = """\
-- ---------- 1. Очистка (скрипт можно запускать повторно) ----------
DROP VIEW  IF EXISTS v_order_totals CASCADE;
DROP VIEW  IF EXISTS v_catalog CASCADE;
DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS stock_items CASCADE;
DROP TABLE IF EXISTS models CASCADE;
DROP TABLE IF EXISTS manufacturers CASCADE;
DROP TABLE IF EXISTS subcategories CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS variants CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS roles CASCADE;

-- ---------- 2. Справочники ----------
CREATE TABLE roles (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(40) NOT NULL UNIQUE CHECK (name <> '')
);

CREATE TABLE categories (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL UNIQUE CHECK (name <> '')
);

CREATE TABLE subcategories (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER     NOT NULL REFERENCES categories(id),
    name        VARCHAR(60) NOT NULL CHECK (name <> ''),
    UNIQUE (category_id, name)
);

CREATE TABLE manufacturers (            -- поле «Производство»
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE CHECK (name <> '')
);

CREATE TABLE variants (                 -- вариант исполнения: цвет корпуса
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(40) NOT NULL UNIQUE CHECK (name <> '')
);

-- ---------- 3. Пользователи ----------
CREATE TABLE users (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login       VARCHAR(40) NOT NULL UNIQUE CHECK (login <> ''),
    last_name   VARCHAR(60) NOT NULL CHECK (last_name <> ''),
    first_name  VARCHAR(60) NOT NULL CHECK (first_name <> ''),
    middle_name VARCHAR(60) NOT NULL DEFAULT '',
    role_id     INTEGER     NOT NULL REFERENCES roles(id)
);

-- ---------- 4. Каталог ----------
CREATE TABLE models (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120) NOT NULL CHECK (name <> ''),
    manufacturer_id INTEGER      NOT NULL REFERENCES manufacturers(id),
    subcategory_id  INTEGER      NOT NULL REFERENCES subcategories(id),
    image           VARCHAR(100) NOT NULL DEFAULT '',          -- пусто = показываем picture.png
    description     TEXT         NOT NULL DEFAULT '',
    composition     TEXT         NOT NULL DEFAULT '',
    base_price      NUMERIC(12,2) NOT NULL CHECK (base_price >= 0), -- = минимальная цена вариантов
    UNIQUE (name, manufacturer_id)                              -- модель = наименование + производство
);

CREATE TABLE stock_items (              -- товарная позиция: модель + вариант
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id   INTEGER       NOT NULL REFERENCES models(id),
    variant_id INTEGER       NOT NULL REFERENCES variants(id),
    quantity   INTEGER       NOT NULL DEFAULT 0 CHECK (quantity >= 0),   -- доступный остаток, шт.
    price      NUMERIC(12,2) NOT NULL CHECK (price >= 0),                -- цена варианта
    UNIQUE (model_id, variant_id)
);

-- ---------- 5. Заказы ----------
CREATE TABLE orders (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date DATE    NOT NULL DEFAULT CURRENT_DATE,
    client_id  INTEGER NOT NULL REFERENCES users(id)
);

CREATE TABLE order_items (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      INTEGER       NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    stock_item_id INTEGER       NOT NULL REFERENCES stock_items(id),
    quantity      INTEGER       NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),   -- историческая цена на момент заказа
    UNIQUE (order_id, stock_item_id)                                -- повторное добавление объединяется
);

-- ---------- 6. Индексы по внешним ключам ----------
CREATE INDEX idx_subcategories_category ON subcategories(category_id);
CREATE INDEX idx_users_role             ON users(role_id);
CREATE INDEX idx_models_manufacturer    ON models(manufacturer_id);
CREATE INDEX idx_models_subcategory     ON models(subcategory_id);
CREATE INDEX idx_stock_items_model      ON stock_items(model_id);
CREATE INDEX idx_stock_items_variant    ON stock_items(variant_id);
CREATE INDEX idx_orders_client          ON orders(client_id);
CREATE INDEX idx_order_items_order      ON order_items(order_id);
CREATE INDEX idx_order_items_stock      ON order_items(stock_item_id);

-- ---------- 7. Представления ----------
CREATE VIEW v_catalog AS                -- модель с категорией, производством и суммарным остатком
SELECT m.id AS model_id, m.name AS model_name, mf.name AS manufacturer,
       c.name AS category, sc.name AS subcategory, m.base_price,
       COALESCE(SUM(si.quantity), 0) AS total_stock
FROM models m
JOIN manufacturers mf ON mf.id = m.manufacturer_id
JOIN subcategories sc ON sc.id = m.subcategory_id
JOIN categories c     ON c.id  = sc.category_id
LEFT JOIN stock_items si ON si.model_id = m.id
GROUP BY m.id, m.name, mf.name, c.name, sc.name, m.base_price;

CREATE VIEW v_order_totals AS           -- итог по каждому заказу
SELECT o.id AS order_id, o.order_date,
       u.last_name || ' ' || u.first_name || ' ' || u.middle_name AS client,
       SUM(oi.quantity * oi.unit_price) AS total
FROM orders o
JOIN users u        ON u.id = o.client_id
JOIN order_items oi ON oi.order_id = o.id
GROUP BY o.id, o.order_date, u.last_name, u.first_name, u.middle_name;
"""

TABLES_WITH_IDS = ["roles", "categories", "subcategories", "manufacturers", "variants",
                   "users", "models", "stock_items", "orders", "order_items"]


def read(name):
    ws = openpyxl.load_workbook(IMPORT / f"{name}_import.xlsx", data_only=True).active
    rows = [list(r) for r in ws.iter_rows(values_only=True)]
    return rows[1:]


def q(v):
    """SQL-литерал."""
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(int(v)) if float(v).is_integer() else repr(float(v))
    return "'" + str(v).replace("'", "''") + "'"


def ids(values):
    """Уникальные значения -> id по порядку появления."""
    out = {}
    for v in values:
        out.setdefault(v, len(out) + 1)
    return out


def insert(table, cols, rows):
    if not rows:
        return ""
    body = ",\n".join("    (" + ", ".join(q(x) for x in r) + ")" for r in rows)
    return f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n{body};\n\n"


def build():
    P, V, S, U, O = (read(n) for n in ("Products", "Variants", "Stock_Items", "Users", "Orders"))

    roles = ids(u[4] for u in U)
    cats = ids(p[0] for p in P)
    subs = ids((p[0], p[1]) for p in P)
    mans = ids(p[4] for p in P)
    variants = ids(v[0] for v in V)
    users = {u[3]: i for i, u in enumerate(U, 1)}
    fio2user = {f"{u[0]} {u[1]} {u[2]}".strip(): users[u[3]] for u in U}
    models = {(p[3], p[4]): i for i, p in enumerate(P, 1)}
    stock = {(s[0], s[1], s[2]): i for i, s in enumerate(S, 1)}

    # ---- проверки целостности (контрольные ситуации из инструкции) ----
    errors = []
    if len(users) != len(U): errors.append("логины пользователей не уникальны")
    if len(models) != len(P): errors.append("модели (наименование+производство) не уникальны")
    if len(stock) != len(S): errors.append("товарные позиции не уникальны")
    for s in S:
        if (s[0], s[1]) not in models: errors.append(f"позиция без модели: {s[:3]}")
        if s[2] not in variants: errors.append(f"неизвестный вариант: {s[2]}")
        if s[3] < 0 or s[4] < 0: errors.append(f"отрицательное значение: {s}")
    minp = defaultdict(list)
    for s in S:
        minp[(s[0], s[1])].append(s[4])
    for p in P:
        if p[7] != min(minp[(p[3], p[4])]): errors.append(f"базовая цена != минимальной: {p[3]}")
        if p[2] and not (IMAGES / p[2]).exists(): errors.append(f"нет файла изображения {p[2]}")
    for o in O:
        if o[2] not in fio2user: errors.append(f"ФИО заказа не найдено среди пользователей: {o[2]}")
        if (o[4], o[5], o[6]) not in stock: errors.append(f"строка заказа без позиции: {o}")
    heads = defaultdict(set)
    for o in O:
        heads[o[0]].add((o[1], o[2]))
    if any(len(v) != 1 for v in heads.values()): errors.append("в заказе расходятся дата или ФИО")
    if errors:
        print("ОШИБКИ ДАННЫХ:\n  " + "\n  ".join(errors))
        sys.exit(1)

    # ---- INSERT-ы ----
    d = [
        insert("roles", ["id", "name"], [(i, n) for n, i in roles.items()]),
        insert("categories", ["id", "name"], [(i, n) for n, i in cats.items()]),
        insert("subcategories", ["id", "category_id", "name"],
               [(i, cats[c], n) for (c, n), i in subs.items()]),
        insert("manufacturers", ["id", "name"], [(i, n) for n, i in mans.items()]),
        insert("variants", ["id", "name"], [(i, n) for n, i in variants.items()]),
        insert("users", ["id", "login", "last_name", "first_name", "middle_name", "role_id"],
               [(i, u[3], u[0], u[1], u[2] or "", roles[u[4]]) for i, u in enumerate(U, 1)]),
        insert("models", ["id", "name", "manufacturer_id", "subcategory_id", "image",
                          "description", "composition", "base_price"],
               [(i, p[3], mans[p[4]], subs[(p[0], p[1])], p[2] or "", p[5] or "", p[6] or "", p[7])
                for i, p in enumerate(P, 1)]),
        insert("stock_items", ["id", "model_id", "variant_id", "quantity", "price"],
               [(i, models[(s[0], s[1])], variants[s[2]], s[3], s[4]) for i, s in enumerate(S, 1)]),
    ]
    order_ids = sorted(heads)
    d.append(insert("orders", ["id", "order_date", "client_id"],
                    [(n, list(heads[n])[0][0].date().isoformat(), fio2user[list(heads[n])[0][1]])
                     for n in order_ids]))
    d.append(insert("order_items", ["id", "order_id", "stock_item_id", "quantity", "unit_price"],
                    [(i, o[0], stock[(o[4], o[5], o[6])], o[7], o[8]) for i, o in enumerate(O, 1)]))
    data = "".join(d)

    seq = "".join(f"SELECT setval(pg_get_serial_sequence('{t}', 'id'), (SELECT MAX(id) FROM {t}));\n"
                  for t in TABLES_WITH_IDS)

    header = """\
-- =====================================================================
--  БД «Мир гаджетов» (продажа персональной электроники), PostgreSQL 13+
--  УП.11, тема 8.  Файл создан скриптом src/db/generate_sql.py из docs-import/*.xlsx
--
--  Запуск:
--     psql -U postgres -c "CREATE DATABASE gadgets_db ENCODING 'UTF8'"
--     psql -U postgres -d gadgets_db -f src/db/mir_gadgetov.sql
--  (pgAdmin: создать БД gadgets_db -> Query Tool -> открыть файл -> F5)
-- =====================================================================

BEGIN;

"""
    footer = f"""
-- ---------- 8. Заполнение данными ----------
-- Остатки в stock_items уже учитывают исходные заказы, повторно они не списываются.
-- unit_price в order_items - историческая цена (в заказе 3 она отличается от текущей).

{data}-- ---------- 9. Сброс счётчиков идентификаторов ----------
-- Данные вставлены с явными id, поэтому счётчики нужно «догнать».
{seq}
COMMIT;

-- ---------- 10. Проверочные запросы ----------
-- SELECT * FROM v_catalog ORDER BY base_price;
-- SELECT * FROM v_order_totals ORDER BY order_id;
"""
    stats = {"roles": len(roles), "categories": len(cats), "subcategories": len(subs),
             "manufacturers": len(mans), "variants": len(variants), "users": len(U), "models": len(P),
             "stock_items": len(S), "orders": len(order_ids), "order_items": len(O)}
    return header + SCHEMA + footer, stats


def to_sqlite(sql):
    """Приводим PostgreSQL-скрипт к виду, понятному SQLite (для файла-копии .db)."""
    s = sql.replace("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                    "INTEGER PRIMARY KEY AUTOINCREMENT")
    s = re.sub(r"\s+CASCADE;", ";", s)
    s = re.sub(r"NUMERIC\(\d+,\d+\)", "NUMERIC", s)
    s = re.sub(r"SELECT setval[^\n]*\n", "", s)
    s = s.replace("BEGIN;\n", "").replace("\nCOMMIT;\n", "\n")
    return s


def main():
    sql, stats = build()
    OUT_SQL.write_text(sql, encoding="utf-8", newline="\n")
    if OUT_DB.exists():
        OUT_DB.unlink()
    con = sqlite3.connect(OUT_DB)
    con.execute("PRAGMA foreign_keys = ON")
    con.executescript(to_sqlite(sql))
    con.commit()
    con.close()
    print("Готово:", OUT_SQL.relative_to(ROOT), "и", OUT_DB.relative_to(ROOT))
    print("Строк по таблицам:", stats)


if __name__ == "__main__":
    main()
